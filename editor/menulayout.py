def apply(mw) -> dict:
    """メニューバーを LAYOUT に組み直す。戻り値: {"menus": [...], "leftover": n, "missing": [...]}"""
    mb = mw.menuBar()
    tops = [a for a in mb.actions() if a.menu() is not None]
    leaves: Dict[str, object] = {}        # 表示名 → QAction
    origin: Dict[int, str] = {}           # id(QAction) → 元のトップのメニュー
    submenus: Dict[str, QMenu] = {}
    sub_leaf: Dict[str, List[object]] = {}

    def walk(m: QMenu, top: str, inside: str = ""):
        for a in m.actions():
            if a.isSeparator():
                continue
            if a.menu() is not None:
                t = _text(a)
                submenus.setdefault(t, a.menu())
                sub_leaf.setdefault(t, [])
                origin.setdefault(id(a.menu().menuAction()), top)
                walk(a.menu(), top, t)
            else:
                t = _text(a)
                leaves.setdefault(t, a)
                origin.setdefault(id(a), top)
                if inside:
                    sub_leaf[inside].append(a)
    for a in tops:
        if a.text() not in KEEP:
            walk(a.menu(), a.text())
    placed = set()
    missing = []
    new_menus: Dict[str, QMenu] = {}

    def fill(dst: QMenu, items: list):
        for it in items:
            if it == SEP:
                if dst.actions() and not dst.actions()[-1].isSeparator():
                    dst.addSeparator()
            elif isinstance(it, tuple) and it[0] == "sub":
                sm = dst.addMenu(it[1])
                fill(sm, it[2])
                if not sm.actions():
                    dst.removeAction(sm.menuAction())
            elif isinstance(it, tuple) and it[0] == "menu":
                m = submenus.get(it[1])
                if m is None:
                    missing.append(it[1])
                    continue
                dst.addMenu(m)
                placed.add(id(m.menuAction()))
                for x in sub_leaf.get(it[1], []):
                    placed.add(id(x))
            else:
                a = leaves.get(it)
                if a is None:
                    missing.append(it)
                    continue
                if id(a) in placed:
                    continue
                dst.addAction(a)
                placed.add(id(a))

    for title, items in LAYOUT:
        m = QMenu(title, mw)
        fill(m, items)
        new_menus[title] = m
    # 載せていない項目（新しい機能・名前が変わったもの）は「その他」へ
    left = 0
    others: Dict[str, QMenu] = {}
    for t, a in leaves.items():
        if id(a) in placed:
            continue
        # サブメニューの中で、そのサブメニューごと移したものは済み
        dst_title = FALLBACK.get(origin.get(id(a), ""), "連携")
        if dst_title not in new_menus:
            dst_title = "連携"
        om = others.get(dst_title)
        if om is None:
            new_menus[dst_title].addSeparator()
            om = new_menus[dst_title].addMenu("その他")
            others[dst_title] = om
        om.addAction(a)
        placed.add(id(a))
        left += 1
    # メニューバーを入れ替え（ウィンドウ・ヘルプはそのまま後ろに）
    keep = [a for a in tops if a.text() in KEEP]
    for a in tops:
        mb.removeAction(a)
    for title, _items in LAYOUT:
        mb.addMenu(new_menus[title])
    for a in keep:
        mb.addAction(a)
    mw._menu_layout_menus = new_menus
    mw._menu_actions = {a.text(): a for a in mb.actions() if a.menu() is not None}    # かんたん / すべて の切り替え用
    return {"menus": [a.text() for a in mb.actions() if a.menu() is not None], "leftover": left, "missing": missing}
